"use client";

import { useSearchParams } from "next/navigation";
import { Suspense, useEffect, useState } from "react";

import { useAuth } from "@/components/auth-provider";
import { PageHeader } from "@/components/common";
import { Alert } from "@/components/ui/alert";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from "@/components/ui/card";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import { api, errorMessage } from "@/lib/api";
import { dateTime } from "@/lib/format";
import type { MfaSetup, MfaStatus } from "@/lib/types";

const REASONS: Record<string, string> = {
  policy: "O administrador da plataforma exige 2FA para todos os usuários.",
  live: "Você tem acesso a contas reais (live): o 2FA é obrigatório.",
  admin: "Super-administradores precisam de 2FA para acessar a Administração.",
};

function RecoveryCodes({ codes, onDone }: { codes: string[]; onDone: () => void }) {
  const [saved, setSaved] = useState(false);
  const [copied, setCopied] = useState(false);
  const text = codes.join("\n");
  const download = () => {
    const url = URL.createObjectURL(new Blob([`Códigos de recuperação ISCTRADE\n\n${text}\n`], { type: "text/plain" }));
    const a = document.createElement("a");
    a.href = url;
    a.download = "isctrade-codigos-recuperacao.txt";
    a.click();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  };
  return (
    <div className="space-y-4">
      <Alert variant="warning">
        Guarde estes códigos em local seguro (gerenciador de senhas ou papel). Cada código funciona <strong>uma única
        vez</strong> se você perder o celular. Eles não serão exibidos novamente.
      </Alert>
      <ol className="grid grid-cols-2 gap-2 rounded-md border p-4 font-mono text-sm" aria-label="Códigos de recuperação">
        {codes.map((c) => (
          <li key={c}>{c}</li>
        ))}
      </ol>
      <div className="flex flex-wrap gap-2">
        <Button
          type="button"
          variant="outline"
          onClick={() =>
            navigator.clipboard
              .writeText(text)
              .then(() => setCopied(true))
              .catch(() => undefined)
          }
        >
          {copied ? "Copiado!" : "Copiar"}
        </Button>
        <Button type="button" variant="outline" onClick={download}>
          Baixar .txt
        </Button>
      </div>
      <label className="flex items-center gap-2 text-sm">
        <input type="checkbox" checked={saved} onChange={(e) => setSaved(e.target.checked)} />
        Guardei os códigos de recuperação
      </label>
      <Button onClick={onDone} disabled={!saved}>
        Concluir
      </Button>
    </div>
  );
}

function Enroll({ onEnabled }: { onEnabled: (codes: string[]) => void }) {
  const [setup, setSetup] = useState<MfaSetup | null>(null);
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);

  async function start() {
    setBusy(true);
    setError(null);
    try {
      setSetup(await api.mfaSetup());
    } catch (e) {
      setError(errorMessage(e));
    } finally {
      setBusy(false);
    }
  }

  async function confirmCode(e: React.FormEvent) {
    e.preventDefault();
    setBusy(true);
    setError(null);
    try {
      const r = await api.mfaEnable(code);
      onEnabled(r.recovery_codes);
    } catch (err) {
      setError(errorMessage(err));
    } finally {
      setBusy(false);
    }
  }

  if (!setup) {
    return (
      <div className="space-y-3">
        <p className="text-sm text-muted-foreground">
          Use um aplicativo autenticador (Google Authenticator, Microsoft Authenticator, Authy, 1Password, Bitwarden…)
          para gerar códigos de 6 dígitos que serão pedidos no login e para operar contas reais.
        </p>
        {error && <Alert variant="destructive">{error}</Alert>}
        <Button onClick={start} disabled={busy}>
          {busy ? "Gerando..." : "Configurar 2FA"}
        </Button>
      </div>
    );
  }

  return (
    <div className="grid gap-6 md:grid-cols-[auto,1fr]">
      <div className="flex flex-col items-center gap-2">
        {/* eslint-disable-next-line @next/next/no-img-element -- data: URI SVG generated by the API */}
        <img
          src={setup.qr_svg}
          alt="QR code para configurar o aplicativo autenticador"
          width={208}
          height={208}
          className="rounded-md bg-white p-2"
        />
      </div>
      <form onSubmit={confirmCode} className="space-y-4">
        <ol className="list-decimal space-y-1 pl-5 text-sm">
          <li>Escaneie o QR code com o aplicativo autenticador.</li>
          <li>
            Ou digite a chave manualmente:{" "}
            <code className="break-all rounded bg-muted px-1.5 py-0.5 text-xs" aria-label="Chave secreta">
              {setup.secret}
            </code>
          </li>
          <li>Digite abaixo o código de 6 dígitos exibido no aplicativo.</li>
        </ol>
        <div className="max-w-xs space-y-1">
          <Label htmlFor="totp-code">Código do aplicativo</Label>
          <Input
            id="totp-code"
            required
            autoFocus
            inputMode="numeric"
            autoComplete="one-time-code"
            pattern="[0-9 ]{6,7}"
            maxLength={7}
            placeholder="123456"
            value={code}
            onChange={(e) => setCode(e.target.value)}
          />
        </div>
        {error && <Alert variant="destructive">{error}</Alert>}
        <div className="flex gap-2">
          <Button type="submit" disabled={busy || code.replace(/\s/g, "").length !== 6}>
            {busy ? "Verificando..." : "Ativar 2FA"}
          </Button>
          <Button type="button" variant="ghost" onClick={start} disabled={busy}>
            Gerar novo QR code
          </Button>
        </div>
      </form>
    </div>
  );
}

function PasswordCodeForm({
  idPrefix,
  submitLabel,
  destructive,
  onSubmit,
}: {
  idPrefix: string;
  submitLabel: string;
  destructive?: boolean;
  onSubmit: (password: string, code: string) => Promise<void>;
}) {
  const [password, setPassword] = useState("");
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  return (
    <form
      className="grid gap-3 sm:grid-cols-[1fr,1fr,auto] sm:items-end"
      onSubmit={async (e) => {
        e.preventDefault();
        setBusy(true);
        setError(null);
        try {
          await onSubmit(password, code);
          setPassword("");
          setCode("");
        } catch (err) {
          setError(errorMessage(err));
        } finally {
          setBusy(false);
        }
      }}
    >
      <div className="space-y-1">
        <Label htmlFor={`${idPrefix}-pw`}>Senha</Label>
        <Input
          id={`${idPrefix}-pw`}
          type="password"
          required
          autoComplete="current-password"
          value={password}
          onChange={(e) => setPassword(e.target.value)}
        />
      </div>
      <div className="space-y-1">
        <Label htmlFor={`${idPrefix}-code`}>Código 2FA ou de recuperação</Label>
        <Input
          id={`${idPrefix}-code`}
          required
          autoComplete="one-time-code"
          value={code}
          onChange={(e) => setCode(e.target.value)}
        />
      </div>
      <Button type="submit" variant={destructive ? "destructive" : "default"} disabled={busy}>
        {submitLabel}
      </Button>
      {error && (
        <Alert variant="destructive" className="sm:col-span-3">
          {error}
        </Alert>
      )}
    </form>
  );
}

function SecurityContent() {
  const { reload } = useAuth();
  const params = useSearchParams();
  const [status, setStatus] = useState<MfaStatus | null>(null);
  const [codes, setCodes] = useState<string[] | null>(null);
  const [notice, setNotice] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  const refresh = () =>
    api
      .mfaStatus()
      .then(setStatus)
      .catch((e) => setError(errorMessage(e)));

  useEffect(() => {
    api
      .mfaStatus()
      .then(setStatus)
      .catch((e) => setError(errorMessage(e)));
  }, []);

  const forced = params.get("obrigatorio") === "1";

  return (
    <div className="max-w-3xl space-y-6">
      <PageHeader
        title="Segurança"
        description="Autenticação em dois fatores (TOTP) e códigos de recuperação."
      />
      {status?.required && !status.enabled && (
        <Alert variant="warning">
          <strong>2FA obrigatório.</strong> {REASONS[status.required_reason ?? ""] ?? ""}{" "}
          {forced && "O restante da plataforma fica bloqueado até a ativação."}
        </Alert>
      )}
      {notice && <Alert variant="success">{notice}</Alert>}
      {error && <Alert variant="destructive">{error}</Alert>}

      <Card>
        <CardHeader className="flex flex-row items-start justify-between space-y-0">
          <div>
            <CardTitle className="text-lg">Autenticação em dois fatores (2FA)</CardTitle>
            <CardDescription>
              Exigida no login e para ações com contas reais
              {status?.live_requires_2fa ? " (criar, ativar ou iniciar conta live e enviar ordens reais)" : ""}.
            </CardDescription>
          </div>
          {status && (
            <Badge variant={status.enabled ? "success" : "warning"}>{status.enabled ? "Ativo" : "Desativado"}</Badge>
          )}
        </CardHeader>
        <CardContent className="space-y-4">
          {!status ? (
            <p className="text-sm text-muted-foreground">Carregando...</p>
          ) : codes ? (
            <RecoveryCodes
              codes={codes}
              onDone={() => {
                setCodes(null);
                setNotice("2FA ativo. Os próximos logins pedirão o código do aplicativo.");
              }}
            />
          ) : status.enabled ? (
            <dl className="grid gap-2 text-sm sm:grid-cols-2">
              <div>
                <dt className="text-muted-foreground">Ativado em</dt>
                <dd>{dateTime(status.enabled_at)}</dd>
              </div>
              <div>
                <dt className="text-muted-foreground">Códigos de recuperação restantes</dt>
                <dd className={status.recovery_codes_remaining <= 2 ? "text-amber-300" : ""}>
                  {status.recovery_codes_remaining} de 10
                </dd>
              </div>
            </dl>
          ) : (
            <Enroll
              onEnabled={(newCodes) => {
                setCodes(newCodes);
                // 2FA is already active on the server: refresh badge, banner and sidebar while the codes stay visible.
                void refresh();
                void reload();
              }}
            />
          )}
        </CardContent>
      </Card>

      {status?.enabled && !codes && (
        <>
          <Card>
            <CardHeader>
              <CardTitle className="text-lg">Gerar novos códigos de recuperação</CardTitle>
              <CardDescription>Os códigos anteriores deixam de funcionar.</CardDescription>
            </CardHeader>
            <CardContent>
              <PasswordCodeForm
                idPrefix="regen"
                submitLabel="Gerar códigos"
                onSubmit={async (pw, code) => {
                  const r = await api.mfaRecoveryCodes(pw, code);
                  setNotice(null);
                  setCodes(r.recovery_codes);
                }}
              />
            </CardContent>
          </Card>
          <Card>
            <CardHeader>
              <CardTitle className="text-lg">Desativar 2FA</CardTitle>
              <CardDescription>
                {status.required
                  ? "O 2FA é obrigatório para o seu usuário e não pode ser desativado. Se perdeu o aplicativo, use um código de recuperação no login e gere novos códigos; sem códigos, peça ao administrador para redefinir o seu 2FA."
                  : "Exige a senha e um código válido. Não recomendado para quem opera contas reais."}
              </CardDescription>
            </CardHeader>
            {!status.required && (
              <CardContent>
                <PasswordCodeForm
                  idPrefix="disable"
                  submitLabel="Desativar 2FA"
                  destructive
                  onSubmit={async (pw, code) => {
                    setStatus(await api.mfaDisable(pw, code));
                    setNotice("2FA desativado.");
                    void reload();
                  }}
                />
              </CardContent>
            )}
          </Card>
        </>
      )}
    </div>
  );
}

export default function SecurityPage() {
  return (
    <Suspense>
      <SecurityContent />
    </Suspense>
  );
}
